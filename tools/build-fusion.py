#!/usr/bin/env python3
"""
Builds src/data/fusionData.js — the Velvet Room's tables — from the
megaten-fusion-tool data (https://github.com/aqiu384/megaten-fusion-tool,
public domain / Unlicense).

    python3 tools/build-fusion.py <path to megaten-fusion-tool/src/app>

What it writes:
  ARCANA_CHART   Arcana × Arcana → result Arcana. Persona 5 Royal's chart
                 first; pairs it lacks (Aeon, Jester) from Persona 4 Golden,
                 then Persona 3 Reload.
  TREASURES      Persona 5 Royal's treasure demons: for each, how many steps
                 up (+) or down (−) inside its Arcana the other Persona moves.
  INHERIT        Persona 5 Royal's inheritance table: for each inheritance
                 type, the skill elements a Persona of that type can inherit.
"""
import json
import os
import sys

APP = sys.argv[1] if len(sys.argv) > 1 else 'src/app'
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'data', 'fusionData.js')

ARCANA = {'Hanged': 'Hanged Man'}
CHARTS = ['p5/data/roy-fusion-chart.json', 'p4/data/golden-fusion-chart.json', 'p3r/data/fusion-chart.json']
# P5R inheritance columns → this extension's skill elements.
COLUMNS = {'phy': 'phys', 'gun': 'gun', 'fir': 'fire', 'ice': 'ice', 'ele': 'elec', 'win': 'wind', 'psy': 'psy',
           'nuk': 'nuke', 'ble': 'bless', 'cur': 'curse', 'ail': 'ailment', 'rec': 'heal'}


def arc(r):
    return ARCANA.get(r, r)


def load(rel):
    with open(os.path.join(APP, rel), encoding='utf-8') as f:
        return json.load(f)


def main():
    chart = {}
    for rel in CHARTS:
        d = load(rel)
        races = d['races']
        for i, row in enumerate(d['table']):
            for j, res in enumerate(row):
                if i == j or res == '-':
                    continue
                a, b, r = arc(races[i]), arc(races[j]), arc(res)
                for x, y in ((a, b), (b, a)):
                    chart.setdefault(x, {}).setdefault(y, r)

    el = load('p5/data/roy-element-chart.json')
    treasures = {}
    for ti, name in enumerate(el['elems']):
        treasures[name] = {arc(race): row[ti] for race, row in zip(el['races'], el['table']) if row[ti]}

    it = load('p5/data/inheritance-types.json')
    inherit = {}
    for t, ratio in zip(it['inherits'], it['ratios']):
        inherit[t] = [COLUMNS[c] for c, ok in zip(it['elems'], ratio) if ok == 'o']

    js = [
        '/**',
        ' * Velvet Room tables — generated by tools/build-fusion.py from the',
        ' * megaten-fusion-tool data (public domain). Do not edit by hand.',
        ' */',
        f'export const ARCANA_CHART = {json.dumps(chart, ensure_ascii=False, sort_keys=True)};',
        f'export const TREASURES = {json.dumps(treasures, ensure_ascii=False)};',
        f'export const INHERIT = {json.dumps(inherit)};',
        '',
    ]
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('\n'.join(js))
    print(f'{len(chart)} Arcana, {len(treasures)} treasures, {len(inherit)} inheritance types → {os.path.normpath(OUT)}')


if __name__ == '__main__':
    main()
